// Hostile draft and Region bingo. Synthetic states only.
const assert=require('node:assert/strict');
const {runtime}=require('./runtime.cjs');
const app=runtime();
app.loadBuild();
app.run(`
  var d=initialRunState({region:'Limgrave + Stormveil',severity:'cursed',includeDlc:true,rules:{draft:true}});
  var c=d.current,o=c.draft.for;
  var p1=tcBuildDraftPick(d,c.id,'chase',1,'Morgan');
  var p1again=tcBuildDraftPick(p1,c.id,'chase',0,'Morgan');
  var p2=tcBuildDraftPick(p1,c.id,'morgan',2,'Chase');
  var bd=initialRunState({region:'Limgrave + Stormveil',severity:'cursed',includeDlc:true,rules:{draft:true,board:true}});
  var bdPicked=tcBuildBountyPick(bd,bd.current.id,bd.board.posts[0].id,'Chase');
  var g=initialRunState({region:'Limgrave + Stormveil',severity:'cursed',includeDlc:true,rules:{bingo:true}});
  var favor0=smithingData(g).favor,s=g;
  for(const i of [0,1,2,3])s=tcBuildBingoMark(s,s.region,i,true,'Chase');
  var beforeLine=smithingData(s).favor;
  var line=tcBuildBingoMark(s,s.region,4,true,'Chase');
  var undoPaid=tcBuildBingoMark(line,line.region,4,false,'Chase');
  var travelled=startNextRegion(line,'Chase','Weeping Peninsula');
  var plain=initialRunState({region:'Limgrave + Stormveil',severity:'cursed',includeDlc:true});
`);
assert.equal(app.run('c.draftPending===true&&o.chase.length===3&&o.morgan.length===3'),true,'three options each');
assert.equal(app.run('new Set([...o.chase,...o.morgan].map(b=>b.name)).size'),6,'six different weapons');
assert.equal(app.run('p1.current.draftPending&&p1.current.chase.name===c.chase.name'),true,'nothing revealed after one pick');
assert.equal(app.run('p1again'),null,'a pick is final');
assert.equal(app.run('!p2.current.draftPending&&p2.current.chase.name===o.chase[1].name&&p2.current.morgan.name===o.morgan[2].name'),true,'both revealed together');
assert.equal(app.run('bd.current.bountyPending&&!bd.current.draft'),true,'with a bounty board, no draft before the pick');
assert.equal(app.run('bdPicked.current.draftPending&&bdPicked.current.draft.for.chase.length===3'),true,'the draft follows the bounty');
assert.equal(app.run('g.bingo.cells.length===25&&g.bingo.cells[12].free&&g.bingo.cells[12].done'),true,'a 5×5 card with a free centre');
assert.equal(app.run('beforeLine===favor0'),true,'no pay before a line');
assert.equal(app.run('smithingData(line).favor-beforeLine'),2,'a line pays 2 Favor');
assert.equal(app.run('line.bingo.paid.length'),1);
assert.equal(app.run('undoPaid'),null,'a paid line keeps its squares');
assert.equal(app.run("travelled.bingo.region==='Weeping Peninsula'&&travelled.bingo.paid.length===0"),true,'a new card for a new region');
assert.equal(app.run('plain.bingo===undefined&&plain.current.draft===undefined'),true,'no twists unless chosen');
console.log('PASS tests/draft-bingo.cjs');

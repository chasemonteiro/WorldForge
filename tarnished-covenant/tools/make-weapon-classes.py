"""Writes src/weapon-classes.js: weapon name -> class, from the Build Lab's
calculator data (weaponType ids) and data/weapons.json (pool name -> calculator
name). Re-run if either file changes."""
import gzip, json, re
from pathlib import Path
root = Path(__file__).resolve().parent.parent
TYPES = {1:'Dagger',3:'Straight Sword',5:'Greatsword',7:'Colossal Sword',9:'Curved Sword',11:'Curved Greatsword',13:'Katana',14:'Twinblade',15:'Thrusting Sword',16:'Heavy Thrusting Sword',17:'Axe',19:'Greataxe',21:'Hammer',23:'Great Hammer',24:'Flail',25:'Spear',28:'Great Spear',29:'Halberd',31:'Reaper',35:'Fist',37:'Claw',39:'Whip',41:'Colossal Weapon',50:'Light Bow',51:'Bow',53:'Greatbow',55:'Crossbow',56:'Ballista',57:'Glintstone Staff',61:'Sacred Seal',65:'Small Shield',67:'Medium Shield',69:'Greatshield',87:'Torch',88:'Hand-to-Hand Art',89:'Perfume Bottle',90:'Thrusting Shield',91:'Throwing Blade',92:'Backhand Blade',93:'Light Greatsword',94:'Great Katana',95:'Beast Claw'}
def key(n): return re.sub(r'\s*\(\+\d+\)$', '', str(n)).replace('’', "'").replace('‘', "'").strip().lower()
calc = {}
for e in json.load(gzip.open(root/'assets/build/weapon-data-v1.17.json.gz'))['weapons']:
    t = TYPES.get(e.get('weaponType'))
    if t and e.get('weaponName'): calc.setdefault(key(e['weaponName']), t)
out = dict(calc)
for w in json.load(open(root/'data/weapons.json'))['weapons']:
    c = calc.get(key(w.get('calculatorName') or w['name']))
    if c:
        out[key(w['name'])] = c
        for r in w.get('regions', []): out[key(r.get('label') or w['name'])] = c
missing = sorted({key(w['name']) for w in json.load(open(root/'data/weapons.json'))['weapons']} - set(out))
body = json.dumps(dict(sorted(out.items())), ensure_ascii=False, separators=(',', ':'))
(root/'src/weapon-classes.js').write_text('/* Generated by tools/make-weapon-classes.py from the calculator data. */\nconst TC_WEAPON_CLASSES=' + body + ';\n')
print(len(out), 'names;', len(missing), 'catalog weapons without a class:', missing[:20])
